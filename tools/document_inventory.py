def project_files() -> list[str]:
    """List tracked and unignored project files via Git; omit deleted paths and duplicates."""
    output = subprocess.check_output(["git", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT, text=True)
    return sorted({path for path in output.splitlines() if (ROOT / path).is_file()})


def escape(value: str) -> str:
    """Escape table separators and newlines in generated reference text."""
    return value.replace("|", "\\|").replace("\n", " ").replace("`", "'")


def python_symbols(tree, prefix: str = ""):
    """Yield nested class/function signatures, docstrings, and inline callback expressions."""
    for node in ast.iter_child_nodes(tree):
        if isinstance(node, ast.ClassDef):
            name = prefix + node.name
            yield name, "class", ast.get_docstring(node) or "Data/model structure; see module contract."
            yield from python_symbols(node, name + ".")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            name = prefix + node.name
            signature = f"({ast.unparse(node.args)})" + (f" -> {ast.unparse(node.returns)}" if node.returns else "")
            yield name, signature, ast.get_docstring(node) or "Internal callback; see enclosing function contract."
            yield from python_symbols(node, name + ".")
        elif isinstance(node, ast.Lambda):
            yield f"{prefix}lambda@{node.lineno}", f"({ast.unparse(node.args)})", "Inline key/callback expression: " + ast.unparse(node.body)
        else:
            yield from python_symbols(node, prefix)


def inventory() -> str:
    """Build Markdown documenting every current project file and Python/JavaScript symbol."""
    files = project_files()
    lines = [MARKER, "", "## Complete project file inventory", "", "| File | Responsibility |", "| --- | --- |"]
    for file in files:
        text = (ROOT / file).read_text(encoding="utf-8")
        purpose = PURPOSES.get(file)
        if file.endswith(".py"):
            purpose = ast.get_docstring(ast.parse(text))
        if not purpose:
            raise ValueError(f"Add an inventory purpose for {file}")
        lines.append(f"| `{file}` | {escape(purpose)} |")
    lines.extend(["", "## Complete function, method, class, and callback inventory", "",
                  "Signatures identify inputs/defaults and annotated returns. Descriptions explain behavior and side effects; the module contracts above define shared error handling, callers, concurrency, and verification. Nested functions use qualified names. Anonymous callbacks include their source expressions. This section is generated from source and checked in CI; semantic documentation still requires human/AI review."])
    for file in files:
        text = (ROOT / file).read_text(encoding="utf-8")
        symbols = []
        if file.endswith(".py"):
            symbols = list(python_symbols(ast.parse(text)))
        elif file.endswith((".js", ".mjs")):
            for match in re.finditer(r"(?:async\s+)?function\s+(\w+)\s*\(([^)]*)\)", text):
                symbols.append((match[1], f"({match[2]})", JS_PURPOSES.get(match[1], "Browser test helper; see source assertions and workflow contract.")))
            for number, line in enumerate(text.splitlines(), 1):
                if "=>" in line:
                    symbols.append((f"callback@{number}", "inline", "Event, mapping, filtering, or test callback in its enclosing workflow: " + line.strip()))
        if symbols:
            lines.extend(["", f"### `{file}`", "", "| Symbol | Signature | Behavior |", "| --- | --- | --- |"])
            for name, signature, description in symbols:
                lines.append(f"| `{name}` | `{escape(signature)}` | {escape(description)} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Update the generated reference, or fail --check when files/symbols have drifted."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "DOCUMENTATION.md"
    existing = path.read_text(encoding="utf-8")
    expected = existing.split(MARKER)[0].rstrip() + "\n\n" + inventory()
    if args.check:
        if existing != expected:
            raise SystemExit("Documentation inventory is stale. Run python tools/document_inventory.py")
        print("Documentation file and symbol inventory is current.")
    else:
        path.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()
